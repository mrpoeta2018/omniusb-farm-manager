def get_comment_pool(mode_name="gaming"):
    """
    Retorna la lista de comentarios según la opción seleccionada:
    - '🎮 Gaming / Apoyo (Default)' o 'gaming': 981 comentarios de gaming y apoyo general
    - '🗳️ Votación 6 Segmentos' o 'votacion': 1000 comentarios específicos de los 6 segmentos y votación
    - '🔥 Mixto (Todos los 2000)' o 'mixto': Los casi 2000 comentarios combinados
    """
    if not mode_name:
        return COMMENTS_GAMING_APOYO
    
    m = str(mode_name).lower()
    if "votaci" in m or "segmento" in m:
        return COMMENTS_VOTACION_6_SEGMENTOS
    elif "mixto" in m or "todo" in m or "2000" in m:
        return COMMENTS_TODOS_MIXTO
    else:
        return COMMENTS_GAMING_APOYO
